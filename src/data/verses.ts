/**
 * Deterministically pick today's verse based on current calendar date (UTC).
 * This ensures every user visiting on the same day sees the exact same verse,
 * and refreshing the page does NOT rotate the verse randomly.
 */
export function getVerseOfTheDay(date: Date = new Date()): VerseOfTheDay {
  const startOfYear = new Date(Date.UTC(date.getUTCFullYear(), 0, 1));
  const diffTime = date.getTime() - startOfYear.getTime();
  const dayOfYear = Math.floor(diffTime / (1000 * 60 * 60 * 24));
  const index = Math.abs(dayOfYear) % DAILY_VERSES.length;
  return DAILY_VERSES[index];
}
